"""Extract print estimates from PrusaSlicer G-code.

Requires `use_relative_e_distances = 1` so each move's E value is the filament it pushes.
"""

import re
from dataclasses import dataclass, field
from typing import Iterable, Optional

from app.slicing.models import FeatureUsage, SliceEstimate


class GcodeParseError(ValueError):
    """G-code is missing the statistics the slicer normally appends."""


_SUPPORT_FEATURES = frozenset({"Support material", "Support material interface"})
_DURATION_PART = re.compile(r"(\d+)\s*([dhms])")
_UNIT_SECONDS = {"d": 86400, "h": 3600, "m": 60, "s": 1}
_E_PARAM = re.compile(r"\bE(-?\d*\.?\d+)")
_XY_PARAM = re.compile(r"\b[XY]-?\d*\.?\d+")
_VERSION = re.compile(r"generated by (\S+) (\S+)")


def parse_duration(text: str) -> int:
    """Parse '1d 2h 3m 4s' style durations into seconds."""
    parts = _DURATION_PART.findall(text)
    if not parts:
        raise GcodeParseError(f"Unrecognised duration: {text!r}")
    return sum(int(amount) * _UNIT_SECONDS[unit] for amount, unit in parts)


@dataclass
class _Accumulator:
    feature: str = "Unknown"
    layer_count: int = 0
    max_z: float = 0.0
    feature_mm: dict[str, float] = field(default_factory=dict)
    stats: dict[str, str] = field(default_factory=dict)
    slicer_name: Optional[str] = None
    slicer_version: Optional[str] = None


def _consume(acc: _Accumulator, line: str) -> None:
    if line.startswith(";"):
        if line.startswith(";TYPE:"):
            acc.feature = line[6:].strip()
        elif line.startswith(";LAYER_CHANGE"):
            acc.layer_count += 1
        elif line.startswith(";Z:"):
            try:
                acc.max_z = max(acc.max_z, float(line[3:]))
            except ValueError:
                pass
        elif line.startswith("; ") and " = " in line:
            key, _, value = line[2:].partition(" = ")
            acc.stats[key.strip()] = value.strip()
        elif acc.slicer_name is None and "generated by" in line:
            match = _VERSION.search(line)
            if match:
                acc.slicer_name, acc.slicer_version = match.group(1), match.group(2)
        return

    # Only moves that travel in XY while pushing filament are extrusions; pure E moves
    # are retract/unretract pairs and wipes retract (negative E).
    if not (line.startswith("G1 ") or line.startswith("G2 ") or line.startswith("G3 ")):
        return
    e_match = _E_PARAM.search(line)
    if e_match is None or not _XY_PARAM.search(line):
        return
    amount = float(e_match.group(1))
    if amount > 0:
        acc.feature_mm[acc.feature] = acc.feature_mm.get(acc.feature, 0.0) + amount


def _stat_float(stats: dict[str, str], key: str) -> float:
    raw = stats.get(key)
    if raw is None:
        raise GcodeParseError(f"G-code is missing '{key}'")
    try:
        # Multi-extruder output is comma separated; sum every tool.
        return sum(float(part) for part in raw.split(","))
    except ValueError as exc:
        raise GcodeParseError(f"Invalid value for '{key}': {raw!r}") from exc


def parse_gcode_lines(lines: Iterable[str]) -> tuple[SliceEstimate, str, str]:
    """Return (estimate, slicer name, slicer version)."""
    acc = _Accumulator()
    for raw in lines:
        _consume(acc, raw.rstrip("\r\n"))

    time_text = acc.stats.get("estimated printing time (normal mode)")
    if time_text is None:
        raise GcodeParseError("G-code is missing the estimated printing time")

    filament_mm = _stat_float(acc.stats, "filament used [mm]")
    filament_cm3 = _stat_float(acc.stats, "filament used [cm3]")
    filament_g = _stat_float(acc.stats, "filament used [g]")

    extruded_total = sum(acc.feature_mm.values())
    grams_per_mm = filament_g / extruded_total if extruded_total > 0 else 0.0
    features = [
        FeatureUsage(
            feature=name,
            filament_mm=round(mm, 2),
            grams=round(mm * grams_per_mm, 3),
        )
        for name, mm in sorted(acc.feature_mm.items(), key=lambda item: -item[1])
    ]
    support_g = sum(f.grams for f in features if f.feature in _SUPPORT_FEATURES)

    estimate = SliceEstimate(
        print_time_s=parse_duration(time_text),
        filament_mm=round(filament_mm, 2),
        filament_cm3=round(filament_cm3, 3),
        filament_g=round(filament_g, 3),
        support_g=round(support_g, 3),
        layer_count=acc.layer_count,
        object_height_mm=round(acc.max_z, 3),
        features=features,
    )
    return estimate, acc.slicer_name or "unknown", acc.slicer_version or "unknown"


def parse_gcode_file(path: str) -> tuple[SliceEstimate, str, str]:
    with open(path, "r", encoding="utf-8", errors="replace") as handle:
        return parse_gcode_lines(handle)
