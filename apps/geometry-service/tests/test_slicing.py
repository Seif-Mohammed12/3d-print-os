def _settings(**process) -> SliceSettings:
    return SliceSettings(
        machine=MachineSettings(bed_x_mm=220, bed_y_mm=220, max_height_mm=250),
        process=ProcessSettings(**process),
    )


class TestConfigBuilder:
    def test_maps_core_settings(self):
        config = build_config(_settings(layer_height_mm=0.28, infill_percent=15))
        assert config["layer_height"] == "0.28"
        assert config["fill_density"] == "15%"
        assert config["gcode_flavor"] == "klipper"
        assert config["bed_shape"] == "0x0,220x0,220x220,0x220"
        assert config["use_relative_e_distances"] == "1"
        assert config["machine_max_acceleration_x"] == "3000,3000"

    def test_first_layer_height_defaults_to_printable_value(self):
        assert build_config(_settings(layer_height_mm=0.1))["first_layer_height"] == "0.2"
        assert build_config(_settings(layer_height_mm=0.28))["first_layer_height"] == "0.28"

    def test_support_modes(self):
        assert build_config(_settings(supports=SupportMode.OFF))["support_material"] == "0"
        config = build_config(_settings(supports=SupportMode.BUILDPLATE_ONLY))
        assert config["support_material"] == "1"
        assert config["support_material_buildplate_only"] == "1"

    def test_rejects_layer_too_thick_for_nozzle(self):
        with pytest.raises(SliceConfigError, match="too thick"):
            build_config(_settings(layer_height_mm=0.4))

    @pytest.mark.parametrize("key", ["post_process", "start_gcode", "end_gcode", "output_filename_format"])
    def test_rejects_dangerous_keys(self, key):
        settings = _settings()
        settings.overrides = {key: "anything"}
        with pytest.raises(SliceConfigError, match="not allowed"):
            build_config(settings)

    def test_validates_override_types_and_ranges(self):
        settings = _settings()
        settings.overrides = {"slowdown_below_layer_time": 8, "ironing": True, "seam_position": "rear"}
        config = build_config(settings)
        assert config["slowdown_below_layer_time"] == "8"
        assert config["ironing"] == "1"
        assert config["seam_position"] == "rear"

        for bad in (
            {"slowdown_below_layer_time": 9999},
            {"ironing": "yes"},
            {"seam_position": "front; rm -rf"},
            {"infill_every_layers": 1.5},
            {"retract_length": True},
        ):
            settings.overrides = bad
            with pytest.raises(SliceConfigError):
                build_config(settings)

    def test_pair_overrides(self):
        settings = _settings()
        settings.overrides = {"machine_max_jerk_x": 8}
        assert build_config(settings)["machine_max_jerk_x"] == "8,8"

    def test_render_rejects_line_breaks(self):
        with pytest.raises(SliceConfigError):
            render_ini({"layer_height": "0.2\npost_process = evil"})


class TestGcodeParser:
    def test_parse_duration(self):
        assert parse_duration("18m 4s") == 1084
        assert parse_duration("1d 2h 3m 4s") == 93784
        with pytest.raises(GcodeParseError):
            parse_duration("soon")

    def test_parses_stats_and_features(self):
        gcode = """; generated by PrusaSlicer 2.6.1+win64 on 2026-10-20
G1 E2 F2400
;LAYER_CHANGE
;Z:0.2
;TYPE:Skirt/Brim
G1 X10 Y10 E1.0
;TYPE:External perimeter
G1 X20 Y10 E3.0
G1 E-0.8 F2400
G1 X30 Y30 F9000
G1 E0.8 F2400
;LAYER_CHANGE
;Z:0.4
;TYPE:Support material
G1 X40 Y30 E4.0
G1 X41 Y30 E-0.2
; filament used [mm] = 8.00
; filament used [cm3] = 0.02
; filament used [g] = 0.80
; estimated printing time (normal mode) = 1h 2m 3s
"""
        estimate, name, version = parse_gcode_lines(gcode.splitlines())
        assert name == "PrusaSlicer"
        assert version == "2.6.1+win64"
        assert estimate.print_time_s == 3723
        assert estimate.filament_g == 0.8
        assert estimate.layer_count == 2
        assert estimate.object_height_mm == 0.4
        by_feature = {f.feature: f for f in estimate.features}
        # Retract/unretract and wipe moves are excluded; 8 mm extruded in total.
        assert by_feature["Support material"].filament_mm == 4.0
        assert by_feature["Support material"].grams == pytest.approx(0.4)
        assert estimate.support_g == pytest.approx(0.4)

    def test_missing_stats_raise(self):
        with pytest.raises(GcodeParseError):
            parse_gcode_lines([";TYPE:Perimeter", "G1 X1 Y1 E1"])


class TestOrientation:
    def test_as_uploaded_is_first_and_poses_are_unique(self):
        mesh = trimesh.creation.box((10, 20, 40))
        candidates = stable_pose_candidates(mesh, 4)
        assert candidates[0].label == "as_uploaded"
        ups = [c.rotation.T @ np.array([0, 0, 1.0]) for c in candidates]
        for i in range(len(ups)):
            for j in range(i + 1, len(ups)):
                assert ups[i] @ ups[j] < 0.999

    def test_apply_rotation_rests_on_bed(self):
        mesh = trimesh.creation.box((10, 20, 40))
        rotated = apply_rotation(mesh, stable_pose_candidates(mesh, 2)[1].rotation)
        assert rotated.bounds[0][2] == pytest.approx(0.0, abs=1e-6)

    def test_fit_on_bed_spins_when_needed(self):
        mesh = apply_rotation(trimesh.creation.box((300, 100, 10)), np.eye(3))
        fits, spin = fit_on_bed(mesh, bed_x=150, bed_y=350, max_height=100)
        assert fits
        assert not np.allclose(spin, np.eye(3))
        assert fit_on_bed(mesh, bed_x=150, bed_y=150, max_height=100)[0] is False


def test_score_prefers_cheaper_estimate():
    base = dict(filament_mm=1, filament_cm3=1, layer_count=1, object_height_mm=1, features=[])
    fast = SliceEstimate(print_time_s=3600, filament_g=10, support_g=0, **base)
    slow = SliceEstimate(print_time_s=7200, filament_g=10, support_g=0, **base)
    weights = SelectionWeights(cost_per_hour=100, cost_per_gram=1, support_penalty_per_gram=0)
    assert score_estimate(fast, weights) < score_estimate(slow, weights)


def _find_slicer():
    candidates = [
        os.environ.get("SLICER_EXECUTABLE"),
        shutil.which("prusa-slicer"),
        shutil.which("prusa-slicer-console"),
        r"C:\Program Files\Prusa3D\PrusaSlicer\prusa-slicer-console.exe",
    ]
    return next((c for c in candidates if c and os.path.exists(c)), None)


SLICER = _find_slicer()
needs_slicer = pytest.mark.skipif(SLICER is None, reason="PrusaSlicer not installed")


@needs_slicer
class TestRealSlicing:
    engine = PrusaSlicerEngine(executable=SLICER or "", timeout_s=120, max_parallel=4)

    def test_cube_estimate_is_physically_plausible(self):
        mesh = trimesh.creation.box((20, 20, 20))
        result = self.engine.slice(
            mesh,
            _settings(supports=SupportMode.OFF),
            OrientationRequest(mode=OrientationMode.AS_IS),
            SelectionWeights(),
        )
        estimate = result.estimate
        # 2 perimeters + 4/4 solid layers + 20% grid of a 20 mm cube in PLA: ~3-6 g.
        assert 3.0 < estimate.filament_g < 6.0
        assert 5 * 60 < estimate.print_time_s < 60 * 60
        assert estimate.layer_count == 100
        assert estimate.object_height_mm == pytest.approx(20.0, abs=0.01)
        assert estimate.support_g == 0
        assert result.slicer.name == "PrusaSlicer"

    def test_overhang_needs_supports_and_auto_orientation_is_never_worse(self):
        post = trimesh.creation.cylinder(radius=3, height=20)
        post.apply_translation((0, 0, 10))
        bar = trimesh.creation.box((40, 10, 5))
        bar.apply_translation((0, 0, 22.5))
        tee = trimesh.util.concatenate([post, bar])

        as_is = self.engine.slice(
            tee, _settings(), OrientationRequest(mode=OrientationMode.AS_IS), SelectionWeights()
        )
        assert as_is.estimate.support_g > 0

        auto = self.engine.slice(
            tee, _settings(), OrientationRequest(mode=OrientationMode.AUTO), SelectionWeights()
        )
        assert len(auto.candidates) > 1
        assert auto.orientation.score <= as_is.orientation.score

    def test_too_large_model_is_rejected(self):
        mesh = trimesh.creation.box((400, 400, 400))
        with pytest.raises(SlicingFailedError) as info:
            self.engine.slice(mesh, _settings(), OrientationRequest(), SelectionWeights())
        assert info.value.code == "model_too_large"
